// Generates public/sw.js: precaches every app file (HTML, JS, CSS, fonts, WASM) so NScribe opens with no internet.
// Run after changing anything in public/:  npm run build
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = 'public';
const skip = new Set(['sw.js', '_headers']);
const files = [];
(function walk(d) {
  for (const n of readdirSync(d)) {
    const p = join(d, n), rel = relative(root, p).split('\\').join('/');
    if (statSync(p).isDirectory()) { if (n === 'models') continue; walk(p); } else if (!skip.has(rel)) files.push(rel);
  }
})(root);
files.sort();
const hash = createHash('sha256');
files.forEach((f) => { hash.update(f); hash.update(readFileSync(join(root, f))); });
const version = hash.digest('hex').slice(0, 12);

const sw = `// GENERATED by scripts/build-sw.mjs. Do not edit by hand.
const CACHE = 'nscribe-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('nscribe-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// Cache-first for our own files. Everything else (model downloads, other sites) passes straight through untouched.
self.addEventListener('fetch', (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/models/')) return;
  e.respondWith(caches.open(CACHE).then(async (c) => {
    const hit = await c.match(req, { ignoreSearch: true });
    if (hit) return hit;
    if (req.mode === 'navigate') { const idx = await c.match('index.html'); if (idx) return idx; }
    try { return await fetch(req); } catch (err) { return new Response('Offline and not cached', { status: 503 }); }
  }));
});
`;
writeFileSync(join(root, 'sw.js'), sw);
console.log('sw.js: ' + files.length + ' files, version ' + version);
